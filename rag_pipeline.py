from sentence_transformers import SentenceTransformer
import faiss
import numpy as np
from prompts import SYSTEM_PROMPT, build_user_prompt
import uuid

class RAGPipeline:
    def __init__(self):
        self.model = SentenceTransformer("all-MiniLM-L6-v2")
        self.dimension = 384
        self.index = faiss.IndexFlatL2(self.dimension)
        self.chunks = []
        self.metadata = []

    def _chunk_text(self, text: str, chunk_size: int = 400, overlap: int = 50):
        words = text.split()
        chunks = []
        for i in range(0, len(words), chunk_size - overlap):
            chunk = " ".join(words[i:i + chunk_size])
            if chunk.strip():
                chunks.append(chunk)
        return chunks

    def add_document(self, text: str, metadata: dict = None):
        doc_id = str(uuid.uuid4())[:8]
        chunks = self._chunk_text(text)
        
        embeddings = self.model.encode(chunks)
        self.index.add(np.array(embeddings).astype("float32"))
        
        for chunk in chunks:
            self.chunks.append(chunk)
            self.metadata.append({
                "doc_id": doc_id,
                "filename": metadata.get("filename", "unknown") if metadata else "unknown"
            })
        
        return doc_id

    def query(self, question: str, top_k: int = 3):
        if len(self.chunks) == 0:
            return {
                "answer": "No documents have been uploaded yet. Please upload a document first.",
                "sources": [],
                "confidence": "low"
            }

        q_emb = self.model.encode([question])
        distances, indices = self.index.search(np.array(q_emb).astype("float32"), top_k)

        retrieved = []
        sources = []
        for idx in indices[0]:
            if idx < len(self.chunks):
                retrieved.append(self.chunks[idx])
                sources.append(self.metadata[idx]["filename"])

        context = "\n\n".join(retrieved)
        prompt = build_user_prompt(context, question)

        # In real production you would call OpenAI / local LLM here.
        # For this demo we return a structured response showing the pipeline works.
        answer = (
            f"Based on the retrieved context, here is the answer to your question:\n\n"
            f"**Question:** {question}\n\n"
            f"**Relevant Context Summary:**\n{context[:500]}...\n\n"
            f"(In production this would be generated by an LLM using the system prompt + context)"
        )

        return {
            "answer": answer,
            "sources": list(set(sources)),
            "confidence": "medium"
        }
